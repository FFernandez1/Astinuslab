"""Contract: both requirements lockfiles are exports of one uv.lock resolution.

``requirements.lock`` is generated by ``uv export`` from ``uv.lock``;
``requirements-dev.lock`` was generated by ``uv pip compile``, which re-resolves
from ``pyproject.toml`` independently. Two resolvers produced two answers and
nothing compared them, so the files drifted: ten packages present in both were
pinned differently -- sqlalchemy, pydantic, fastapi, uvicorn and libvirt-python
among them -- meaning CI never exercised the dependency set the release ships.
The drift also carried starlette 1.0.0 and python-multipart 0.0.27, seven
advisories, into the backend and frontend CI jobs and the nightly real-host job
while production shipped the fixed versions.

This module is the cheap half of the fix: it needs no uv, so it runs in the
ordinary unit job on every push. The authoritative half lives in the
``dependency-audit`` CI job, which regenerates both files with a pinned uv and
fails on any diff.

``KNOWN_DEV_DRIFT`` carries the packages still mismatched at the time this test
landed, so the gate could ship green ahead of the regeneration that empties it.
Entries are asserted to be *actually* drifting, so the list cannot outlive the
problem it documents.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
UV_LOCK = ROOT / "uv.lock"
PROD_LOCK = ROOT / "requirements.lock"
DEV_LOCK = ROOT / "requirements-dev.lock"

_PIN = re.compile(r"^([A-Za-z0-9._-]+)==([^\s;]+)")

# Emptied once both requirements files became exports of one uv.lock resolution.
# Re-populating this is a regression: fix the lockfiles, do not widen the gate.
KNOWN_DEV_DRIFT: frozenset[str] = frozenset()

pytestmark = [pytest.mark.unit]


def _canonical(name: str) -> str:
    return name.lower().replace("_", "-")


def _requirements_pins(path: Path) -> dict[str, str]:
    pins: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _PIN.match(line)
        if match:
            pins[_canonical(match.group(1))] = match.group(2)
    return pins


def _uv_lock_versions() -> dict[str, str]:
    lock = tomllib.loads(UV_LOCK.read_text(encoding="utf-8"))
    return {_canonical(pkg["name"]): pkg["version"] for pkg in lock["package"] if "version" in pkg}


def test_lockfiles_are_non_empty() -> None:
    """A parse that silently yields nothing would make every other test vacuous."""
    assert len(_requirements_pins(PROD_LOCK)) > 20
    assert len(_requirements_pins(DEV_LOCK)) > 40
    assert len(_uv_lock_versions()) > 40


def test_production_lockfile_is_a_faithful_export_of_uv_lock() -> None:
    """requirements.lock is what deploy/install.sh installs; it has no drift allowance."""
    resolved = _uv_lock_versions()
    offenders = [
        f"{name}: requirements.lock={version} uv.lock={resolved.get(name, '<absent>')}"
        for name, version in sorted(_requirements_pins(PROD_LOCK).items())
        if resolved.get(name) != version
    ]

    assert not offenders, "requirements.lock disagrees with uv.lock:\n  " + "\n  ".join(offenders)


def test_dev_lockfile_is_a_faithful_export_of_uv_lock() -> None:
    resolved = _uv_lock_versions()
    offenders = [
        f"{name}: requirements-dev.lock={version} uv.lock={resolved.get(name, '<absent>')}"
        for name, version in sorted(_requirements_pins(DEV_LOCK).items())
        if name not in KNOWN_DEV_DRIFT and resolved.get(name) != version
    ]

    assert not offenders, "requirements-dev.lock disagrees with uv.lock:\n  " + "\n  ".join(offenders)


def test_known_dev_drift_entries_are_still_drifting() -> None:
    """The allowance may not outlive the drift it documents."""
    resolved = _uv_lock_versions()
    dev = _requirements_pins(DEV_LOCK)

    absent = sorted(name for name in KNOWN_DEV_DRIFT if name not in dev)
    assert not absent, f"KNOWN_DEV_DRIFT names packages no longer in requirements-dev.lock: {absent}"

    settled = sorted(name for name in KNOWN_DEV_DRIFT if resolved.get(name) == dev[name])
    assert not settled, f"These now match uv.lock -- drop them from KNOWN_DEV_DRIFT: {settled}"


def test_shared_pins_agree_between_the_two_lockfiles() -> None:
    """The symptom that made the drift matter: CI installing different versions
    of sqlalchemy, pydantic, fastapi and uvicorn than the release ships."""
    prod = _requirements_pins(PROD_LOCK)
    dev = _requirements_pins(DEV_LOCK)
    offenders = [
        f"{name}: requirements.lock={prod[name]} requirements-dev.lock={dev[name]}"
        for name in sorted(set(prod) & set(dev))
        if name not in KNOWN_DEV_DRIFT and prod[name] != dev[name]
    ]

    assert not offenders, "the two lockfiles pin the same package differently:\n  " + "\n  ".join(offenders)
